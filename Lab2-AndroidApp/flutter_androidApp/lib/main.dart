Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  try {
    await dotenv.load(fileName: '.env');
  } catch (e) {
    debugPrint('Could not load .env file: $e');
  }

  var firebaseReady = false;
  try {
    // Reads android/app/google-services.json (generated by the Google
    // Services Gradle plugin); no firebase_options.dart is required on Android.
    await Firebase.initializeApp();
    firebaseReady = true;
    debugPrint('Firebase initialized.');
  } catch (e) {
    // Visible failure: services below degrade to local-only and say so.
    debugPrint('FIREBASE INIT FAILED (missing google-services.json?): $e');
  }

  if (firebaseReady) {
    // Report uncaught framework and async errors to Crashlytics.
    FlutterError.onError = (details) {
      FlutterError.presentError(details);
      FirebaseCrashlytics.instance.recordFlutterFatalError(details);
    };
    PlatformDispatcher.instance.onError = (error, stack) {
      FirebaseCrashlytics.instance.recordError(error, stack, fatal: true);
      return true;
    };
  }

  final locator = ServiceLocator.instance;

  // Defaults are applied locally and the fetch is bounded, so a slow network
  // can never hold the first frame.
  await locator.remoteConfigService
      .initialize()
      .timeout(const Duration(seconds: 5), onTimeout: () {});

  runApp(const AttendanceApp());

  // The permission prompt can wait for the user, so it must not block runApp.
  unawaited(locator.messagingService.initialize());
}

class AttendanceApp extends StatefulWidget {
  const AttendanceApp({super.key});

  @override
  State<AttendanceApp> createState() => _AttendanceAppState();
}

class _AttendanceAppState extends State<AttendanceApp> {
  final ServiceLocator _locator = ServiceLocator.instance;
  late final _AuthRefresh _authRefresh;
  late final GoRouter _router;
  late final AppLifecycleListener _lifecycle;
  StreamSubscription<PushNotificationMessage>? _openedSub;

  /// Destination remembered while the user is signed out (deep link or a
  /// notification tapped on a cold start); used right after login.
  String? _pendingRoute;

  @override
  void initState() {
    super.initState();
    _authRefresh = _AuthRefresh(_locator.authService.authStateChanges);

    _router = GoRouter(
      initialLocation: '/login',
      refreshListenable: _authRefresh,
      redirect: _guard,
      routes: _routes(),
    );

    // Notification tapped while the app was in the background / terminated.
    _openedSub = _locator.messagingService.onNotificationOpened.listen(_openFromNotification);
    final launch = _locator.messagingService.takeLaunchNotification();
    if (launch != null) _openFromNotification(launch);

    _lifecycle = AppLifecycleListener(
      onResume: () => _locator.messagingService.refreshHistory(),
    );
  }

  @override
  void dispose() {
    _openedSub?.cancel();
    _lifecycle.dispose();
    _authRefresh.dispose();
    _router.dispose();
    super.dispose();
  }

  /// Blocks every screen except /login until a real Firebase session exists.
  String? _guard(BuildContext context, GoRouterState state) {
    final signedIn = _locator.authService.currentUser != null;
    final atLogin = state.matchedLocation == '/login';
    if (!signedIn && !atLogin) {
      _pendingRoute = state.uri.toString();
      return '/login';
    }
    return null;
  }

  void _openFromNotification(PushNotificationMessage message) {
    _locator.messagingService.takeLaunchNotification();
    final route = routeForNotification(message);
    if (_locator.authService.currentUser == null) {
      _pendingRoute = route;
      return;
    }
    _router.go(route);
  }

  String _postLoginRoute() {
    final route = _pendingRoute ?? '/home';
    _pendingRoute = null;
    return route;
  }

  /// Creates a view model once per route entry and disposes it with the route.
  Widget _screen<T extends ChangeNotifier>({
    Key? key,
    required T Function() create,
    required Widget Function(T viewModel) builder,
  }) {
    return ChangeNotifierProvider<T>(
      key: key,
      create: (_) => create(),
      child: Builder(builder: (context) => builder(context.read<T>())),
    );
  }

  List<RouteBase> _routes() {
    final l = _locator;
    return [
      GoRoute(
        path: '/login',
        builder: (context, state) => _screen<AuthViewModel>(
          create: l.createAuthViewModel,
          builder: (vm) => LoginPage(
            viewModel: vm,
            loggedOut: state.uri.queryParameters['logout'] == '1',
            postLoginRoute: _postLoginRoute,
          ),
        ),
      ),
      ShellRoute(
        builder: (context, state, child) => AppShell(child: child),
        routes: [
          GoRoute(
            path: '/home',
            builder: (context, state) => _screen<HomeViewModel>(
              create: l.createHomeViewModel,
              builder: (vm) => HomePage(
                viewModel: vm,
                onSessionSelected: (id) => context.go('/attendance/$id'),
              ),
            ),
          ),
          GoRoute(
            path: '/take-attendance',
            builder: (context, state) => _screen<AttendanceBrowseViewModel>(
              create: l.createAttendanceBrowseViewModel,
              builder: (vm) => AttendanceBrowsePage(
                viewModel: vm,
                onSessionSelected: (s) => context.go('/attendance/${s.id}'),
              ),
            ),
          ),
          GoRoute(
            path: '/attendance/:sessionId',
            builder: (context, state) {
              final sessionId = state.pathParameters['sessionId']!;
              return _screen<AttendanceDetailViewModel>(
                key: ValueKey('attendance_$sessionId'),
                create: () => l.createAttendanceDetailViewModel(sessionId),
                builder: (vm) => AttendanceDetailPage(
                  viewModel: vm,
                  onAttendanceSaved: () => l.statsService.load(force: true),
                ),
              );
            },
          ),
          GoRoute(
            path: '/my-classes',
            builder: (context, state) => _screen<MyClassesViewModel>(
              create: l.createMyClassesViewModel,
              builder: (vm) => MyClassesPage(
                viewModel: vm,
                onSessionSelected: (id) => context.go('/attendance/$id'),
              ),
            ),
          ),
          GoRoute(
            path: '/timetable',
            builder: (context, state) => _screen<TimetableViewModel>(
              create: l.createTimetableViewModel,
              builder: (vm) => TimetablePage(
                viewModel: vm,
                onSessionSelected: (id) => context.go('/attendance/$id'),
              ),
            ),
          ),
          GoRoute(
            path: '/reports',
            builder: (context, state) => _screen<ReportsViewModel>(
              create: l.createReportsViewModel,
              builder: (vm) => ReportsPage(viewModel: vm),
            ),
          ),
          GoRoute(
            path: '/fap-sync',
            builder: (context, state) => _screen<ExportViewModel>(
              create: l.createExportViewModel,
              builder: (vm) => ExportPage(viewModel: vm),
            ),
          ),
          GoRoute(
            path: '/ai-assistant',
            builder: (context, state) => _screen<AiAssistantViewModel>(
              create: l.createAiAssistantViewModel,
              builder: (vm) => AiAssistantPage(viewModel: vm),
            ),
          ),
          GoRoute(
            path: '/notifications',
            builder: (context, state) => _screen<NotificationsViewModel>(
              create: l.createNotificationsViewModel,
              builder: (vm) => NotificationsPage(viewModel: vm),
            ),
          ),
          GoRoute(
            path: '/profile',
            builder: (context, state) => _screen<ProfileViewModel>(
              create: l.createProfileViewModel,
              builder: (vm) => ProfilePage(viewModel: vm),
            ),
          ),
          GoRoute(
            path: '/settings',
            builder: (context, state) => _screen<SettingsViewModel>(
              create: l.createSettingsViewModel,
              builder: (vm) => SettingsPage(viewModel: vm),
            ),
          ),
        ],
      ),
    ];
  }

  @override
  Widget build(BuildContext context) {
    return Provider<ServiceLocator>.value(
      value: _locator,
      child: MaterialApp.router(
        title: 'AttendEase - FPT Academic Attendance',
        debugShowCheckedModeBanner: false,
        theme: AppTheme.light,
        themeMode: ThemeMode.light,
        scrollBehavior: const _NoStretchScrollBehavior(),
        routerConfig: _router,
      ),
    );
  }
}

/// Disables the Android 12+ stretch overscroll effect (and the glow) so lists
/// stop at the first/last item instead of stretching the whole page.
class _NoStretchScrollBehavior extends MaterialScrollBehavior {
  const _NoStretchScrollBehavior();

  @override
  Widget buildOverscrollIndicator(
    BuildContext context,
    Widget child,
    ScrollableDetails details,
  ) => child;

  @override
  ScrollPhysics getScrollPhysics(BuildContext context) =>
      const ClampingScrollPhysics();
}

/// Re-runs the router redirect whenever Firebase Auth state changes, so a
/// sign-out (or expired session) immediately sends the user back to /login.
class _AuthRefresh extends ChangeNotifier {
  late final StreamSubscription<Object?> _sub;

  _AuthRefresh(Stream<Object?> stream) {
    _sub = stream.listen((_) => notifyListeners());
  }

  @override
  void dispose() {
    _sub.cancel();
    super.dispose();
  }
}
